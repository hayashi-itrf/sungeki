use std::{fs, path::Path};
#[path = "../api_types.rs"]
mod api_types;
use sungeki_editor::Command;
use sungeki_project::*;
use sungeki_protocol::*;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let check = std::env::args().any(|arg| arg == "--check");
    let mut types = String::from("// Generated by sungeki-protocol. Do not edit.\n");
    for declaration in api_types::declarations() {
        types += "export ";
        for line in declaration.lines() {
            types += line.trim_end();
            types.push('\n');
        }
    }
    let schema = serde_json::json!({
        "preset_draft": schemars::schema_for!(Preset),
        "project_draft": schemars::schema_for!(Project),
        "command_draft": schemars::schema_for!(Command),
        "request": schemars::schema_for!(Request),
        "response": schemars::schema_for!(Response),
        "host_info": schemars::schema_for!(HostInfo),
        "error": schemars::schema_for!(ApiError),
    });
    let files = [
        ("packages/api-client/src/generated.ts", types),
        (
            "docs/generated/protocol.schema.json",
            serde_json::to_string_pretty(&schema)? + "\n",
        ),
    ];
    for (relative, contents) in files {
        let path = root.join(relative);
        if check {
            if fs::read_to_string(&path)? != contents {
                return Err(format!("生成物が古くなっています: {relative}").into());
            }
        } else {
            fs::create_dir_all(path.parent().unwrap())?;
            fs::write(path, contents)?;
        }
    }
    Ok(())
}
