#[path = "irodori/common.rs"]
mod common;
use common::source;
use sungeki_project::PronunciationEntry;
use sungeki_speech::irodori::PreparedIrodoriInput;

#[test]
fn capture_owns_inputs_and_dictionary_application() {
    let mut source = source();
    let mut dictionary = vec![PronunciationEntry {
        written: "API".into(),
        spoken: "エーピーアイ".into(),
    }];
    let input = PreparedIrodoriInput::new("APIです", None, &dictionary, &source).unwrap();
    let hash = input.fingerprint().to_owned();
    source.settings.seed = 99;
    dictionary[0].spoken = "変更".into();
    assert_eq!(input.audio_source().settings.seed, 42);
    assert_eq!(input.resolved().text, "エーピーアイです");
    assert_eq!(input.resolved().applied[0].dictionary_index, 0);
    assert_eq!(input.dictionary()[0].spoken, "エーピーアイ");
    assert_eq!(input.subtitle(), "APIです");
    assert_eq!(input.spoken(), None);
    assert_eq!(input.fingerprint(), hash);
}
#[test]
fn synthesis_settings_and_originals_change_the_fingerprint() {
    let base = PreparedIrodoriInput::new("字幕", Some("よみ"), &[], &source()).unwrap();
    for mode in 0..7 {
        let mut changed = source();
        match mode {
            0 => changed.settings.seed += 1,
            1 => changed.settings.caption = Some("穏やかに".into()),
            2 => changed.settings.num_steps += 1,
            3 => changed.identity.codec_manifest_sha256 = "f".repeat(64),
            4 => changed.identity.voice_manifest_sha256 = "f".repeat(64),
            5 => changed.metadata_sha256 = "f".repeat(64),
            _ => changed.identity.model_manifest_sha256 = "f".repeat(64),
        }
        assert_ne!(
            base.fingerprint(),
            PreparedIrodoriInput::new("字幕", Some("よみ"), &[], &changed)
                .unwrap()
                .fingerprint()
        );
    }
    assert_ne!(
        base.fingerprint(),
        PreparedIrodoriInput::new("別字幕", Some("よみ"), &[], &source())
            .unwrap()
            .fingerprint()
    );
    assert_ne!(
        base.fingerprint(),
        PreparedIrodoriInput::new("字幕", Some("べつのよみ"), &[], &source())
            .unwrap()
            .fingerprint()
    );
}
#[test]
fn invalid_text_and_originals_are_rejected_before_dispatch() {
    for text in ["".into(), "bad\0text".into(), "あ".repeat(4097)] {
        assert!(PreparedIrodoriInput::new(&text, None, &[], &source()).is_err());
    }
    assert!(PreparedIrodoriInput::new("字幕", Some(""), &[], &source()).is_err());
    let mut bad = source();
    bad.identity.codec_manifest_sha256.clear();
    assert!(PreparedIrodoriInput::new("字幕", None, &[], &bad).is_err());
}
#[test]
fn decoded_wav_must_match_the_captured_format() {
    let input = PreparedIrodoriInput::new("確認", None, &[], &source()).unwrap();
    for rate in [24000, 48000] {
        let mut bytes = std::io::Cursor::new(Vec::new());
        let spec = hound::WavSpec {
            channels: 1,
            sample_rate: rate,
            bits_per_sample: 16,
            sample_format: hound::SampleFormat::Int,
        };
        let mut writer = hound::WavWriter::new(&mut bytes, spec).unwrap();
        for _ in 0..240 {
            writer.write_sample(100i16).unwrap();
        }
        writer.finalize().unwrap();
        assert_eq!(
            input.verify_audio(bytes.into_inner()).is_ok(),
            rate == 24000
        );
    }
}

#[test]
fn python_worker_float_wav_is_accepted_without_sample_loss() {
    // Synthetic, non-TTS output generated by workers/irodori/audio.py.
    let bytes = include_bytes!("../../../tests/fixtures/irodori-float.wav").to_vec();
    let mut original = source();
    original.identity.sample_rate = 48000;
    let input = PreparedIrodoriInput::new("検査", None, &[], &original).unwrap();
    let wav = input.verify_audio(bytes.clone()).unwrap();
    assert_eq!(wav.info().frames, 5);
    assert_eq!(wav.info().duration_us, 105);
    assert!(wav.info().is_float);
    assert_eq!(wav.info().bits_per_sample, 32);
    assert_eq!(wav.bytes(), bytes);
    let mut broken = bytes;
    broken[58..62].copy_from_slice(&f32::NAN.to_le_bytes());
    assert_eq!(
        input.verify_audio(broken).unwrap_err(),
        sungeki_media::WavError::NonFiniteSample
    );
}
