export type CollectionMessage = keyof typeof english;
export function collectionText(message: CollectionMessage, values: Record<string, string | number> = {}, language = locale.current): string {
  const text = language === 'en' ? english[message] : message;
  return text.replace(/\{(\w+)\}/g, (placeholder, key: string) => key in values ? String(values[key]) : placeholder);
}
